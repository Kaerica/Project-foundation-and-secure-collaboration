const { Pool } = require('pg')
const { products: initialProducts, validateProduct, validateQuantity } = require('./products')

const LOW_STOCK_THRESHOLD = 20
const INITIALIZE_LOCK_ID = 1729001

function createProductStore ({
  pool = new Pool({
    ssl: process.env.PGSSL === 'true' ? { rejectUnauthorized: true } : false,
    connectionTimeoutMillis: 5000
  })
} = {}) {
  async function initialize () {
    const client = await pool.connect()

    try {
      await client.query('BEGIN')
      await client.query('SELECT pg_advisory_xact_lock($1)', [INITIALIZE_LOCK_ID])
      await client.query(`
        CREATE TABLE IF NOT EXISTS products (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          name TEXT NOT NULL CHECK (char_length(btrim(name)) > 0),
          price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
          quantity INTEGER NOT NULL CHECK (quantity >= 0)
        )
      `)

      const values = []
      const placeholders = initialProducts.map((product, index) => {
        const offset = index * 3
        values.push(product.name, product.price, product.quantity)
        return `($${offset + 1}::text, $${offset + 2}::numeric, $${offset + 3}::integer)`
      })

      await client.query(`
        INSERT INTO products (name, price, quantity)
        SELECT seed.name, seed.price, seed.quantity
        FROM (VALUES ${placeholders.join(', ')}) AS seed(name, price, quantity)
        WHERE NOT EXISTS (SELECT 1 FROM products)
      `, values)

      await client.query('COMMIT')
    } catch (error) {
      await client.query('ROLLBACK')
      throw error
    } finally {
      client.release()
    }
  }

  async function listProducts () {
    const result = await pool.query(
      'SELECT id, name, price, quantity FROM products ORDER BY id'
    )
    return result.rows.map(mapProduct)
  }

  async function addProduct (name, price, quantity) {
    validateProduct(name, price, quantity)
    const result = await pool.query(
      'INSERT INTO products (name, price, quantity) VALUES ($1, $2, $3) RETURNING id, name, price, quantity',
      [name.trim(), price, quantity]
    )
    return mapProduct(result.rows[0])
  }

  async function updateQuantity (productId, quantity) {
    validateQuantity(quantity)

    if (!Number.isInteger(productId) || productId < 1) {
      throw new Error('Product not found.')
    }

    const result = await pool.query(
      'UPDATE products SET quantity = $1 WHERE id = $2 RETURNING id, name, price, quantity',
      [quantity, productId]
    )

    if (result.rowCount === 0) {
      throw new Error('Product not found.')
    }

    const product = mapProduct(result.rows[0])
    return `Updated ${product.name} quantity to ${product.quantity}.`
  }

  async function getLowStockProducts () {
    const result = await pool.query(
      'SELECT id, name, price, quantity FROM products WHERE quantity <= $1 ORDER BY id',
      [LOW_STOCK_THRESHOLD]
    )
    return result.rows.map(mapProduct)
  }

  return {
    initialize,
    listProducts,
    addProduct,
    updateQuantity,
    getLowStockProducts,
    checkConnection: async () => {
      await pool.query('SELECT 1')
    },
    close: () => pool.end()
  }
}

function mapProduct (row) {
  return {
    id: row.id,
    name: row.name,
    price: Number(row.price),
    quantity: row.quantity
  }
}

module.exports = { createProductStore }
